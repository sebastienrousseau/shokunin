//! # ssg-rpc — Edge RPC for SSG
//!
//! Tracking issue: [#548] — `feat(edge): Edge RPC — JSON-over-POST
//! with shared TS schema`.
//!
//! ## What this crate gives you
//!
//! * A `#[ssg_rpc]` proc-macro you stick on a free function.
//! * A static dispatch table that maps the function's name to a JSON
//!   trampoline (`String` → `Result<String, RpcError>`).
//! * A schema producer that emits TypeScript declarations into
//!   `dist/.ssg/rpc.d.ts` at build time so the matching JS client is
//!   fully typed end-to-end.
//!
//! ## Wire format
//!
//! Each registered RPC is reachable at `POST /__rpc/<fn_name>`. The
//! body is the JSON-encoded `Input`. Responses are:
//!
//! | Status | Body                                  | When                       |
//! |--------|---------------------------------------|----------------------------|
//! | 200    | JSON-encoded `Output`                 | `Result::Ok`               |
//! | 400    | `{"error": "..."}` (bad request)      | malformed payload          |
//! | 404    | `{"error": "unknown rpc"}`            | unknown name (no leak)     |
//! | 405    | `{"error": "method not allowed"}`     | non-POST verb              |
//! | 500    | `{"error": "..."}`                    | handler returned `Err`     |
//!
//! ## Locked-in design decisions
//!
//! * **JSON, not tRPC**. The 2-3 KB tRPC runtime is too heavy for an
//!   edge-static target — we ship `web/rpc.js` at < 1 KB minified.
//! * **POST only**. GET would invite CDN caching surprises.
//! * **Unauthenticated by default**. Authentication is the user's
//!   responsibility via a middleware layer they wrap around the
//!   dispatcher (see `RpcError::Unauthorized` for the canonical
//!   shape).
//!
//! [#548]: https://github.com/sebastienrousseau/static-site-generator/issues/548

