/// Canonical error type returned by every `#[ssg_rpc]` function.
///
/// The variant names are deliberately stable — the JSON dispatcher
/// uses them to choose an HTTP status code, so renaming would be a
/// wire-protocol break.
///
/// # Examples
///
/// ```
/// use ssg_rpc::RpcError;
///
/// let err = RpcError::BadRequest("missing field".into());
/// assert_eq!(err.to_string(), "bad request: missing field");
/// assert_eq!(err.status_code(), 400);
/// ```
#[derive(Debug, Error)]
pub enum RpcError {
    /// Malformed input payload (HTTP 400). Includes the parser error
    /// for developer ergonomics; do not leak this to untrusted users
    /// without sanitising first.
    #[error("bad request: {0}")]
    BadRequest(String),

    /// Caller is not allowed (HTTP 401). Generated by user-provided
    /// middleware; the dispatcher itself is unauthenticated.
    #[error("unauthorized")]
    Unauthorized,

    /// Resource not found in the handler (HTTP 404). Distinct from
    /// "unknown RPC name", which is generated by the dispatcher
    /// itself.
    #[error("not found")]
    NotFound,

    /// Generic 5xx — handler is broken.
    #[error("internal error: {0}")]
    Internal(String),
}

impl RpcError {
    /// Maps the error to the HTTP status the dispatcher should
    /// return. The choice of integer (vs `http::StatusCode`) keeps
    /// this crate dependency-free for WASM targets that can't link
    /// the `http` crate at runtime.
    ///
    /// # Examples
    ///
    /// ```
    /// use ssg_rpc::RpcError;
    ///
    /// assert_eq!(RpcError::BadRequest("x".into()).status_code(), 400);
    /// assert_eq!(RpcError::Unauthorized.status_code(), 401);
    /// assert_eq!(RpcError::NotFound.status_code(), 404);
    /// assert_eq!(RpcError::Internal("boom".into()).status_code(), 500);
    /// ```
    #[must_use]
    pub const fn status_code(&self) -> u16 {
        match self {
            Self::BadRequest(_) => 400,
            Self::Unauthorized => 401,
            Self::NotFound => 404,
            Self::Internal(_) => 500,
        }
    }

    /// Serialises to the standard `{"error": "..."}` wire body that
    /// the JS client knows how to surface.
    ///
    /// # Examples
    ///
    /// ```
    /// use ssg_rpc::RpcError;
    ///
    /// let body = RpcError::NotFound.to_wire_body();
    /// assert_eq!(body, r#"{"error":"not found"}"#);
    ///
    /// // Quotes and backslashes in the message are escaped so the
    /// // output is always valid JSON.
    /// let tricky = RpcError::BadRequest(r#"oops "x" \n"#.into());
    /// let v: serde_json::Value =
    ///     serde_json::from_str(&tricky.to_wire_body()).unwrap();
    /// assert_eq!(v["error"], r#"bad request: oops "x" \n"#);
    /// ```
    #[must_use]
    pub fn to_wire_body(&self) -> String {
        // Hand-rolled to avoid pulling a full `serde_json::to_string`
        // round-trip for a one-field object — also guarantees we
        // never emit an unbalanced brace on a serialisation failure.
        let msg = self.to_string();
        let escaped = msg.replace('\\', "\\\\").replace('"', "\\\"");
        format!("{{\"error\":\"{escaped}\"}}")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn status_codes_are_stable() {
        assert_eq!(RpcError::BadRequest("x".into()).status_code(), 400);
        assert_eq!(RpcError::Unauthorized.status_code(), 401);
        assert_eq!(RpcError::NotFound.status_code(), 404);
        assert_eq!(RpcError::Internal("x".into()).status_code(), 500);
    }

    #[test]
    fn wire_body_escapes_quotes_and_backslashes() {
        let err = RpcError::BadRequest(r#"oops "quoted" \n"#.into());
        let body = err.to_wire_body();
        assert!(body.starts_with("{\"error\":\""));
        assert!(body.ends_with("\"}"));
        assert!(body.contains(r#"\""#));
        assert!(body.contains(r"\\"));
    }

    #[test]
    fn wire_body_is_round_trippable_json() {
        let err = RpcError::Internal("boom".into());
        let body = err.to_wire_body();
        let parsed: serde_json::Value = serde_json::from_str(&body).unwrap();
        assert_eq!(parsed["error"], "internal error: boom");
    }

    #[test]
    fn error_display_messages_are_stable() {
        // Display strings are part of the on-the-wire body — renaming
        // would silently break JS clients that pattern-match them.
        assert_eq!(
            RpcError::BadRequest("nope".into()).to_string(),
            "bad request: nope"
        );
        assert_eq!(RpcError::Unauthorized.to_string(), "unauthorized");
        assert_eq!(RpcError::NotFound.to_string(), "not found");
        assert_eq!(
            RpcError::Internal("boom".into()).to_string(),
            "internal error: boom"
        );
    }

    #[test]
    fn wire_body_for_unauthorized_is_valid_json() {
        let body = RpcError::Unauthorized.to_wire_body();
        let v: serde_json::Value = serde_json::from_str(&body).unwrap();
        assert_eq!(v["error"], "unauthorized");
    }

    #[test]
    fn wire_body_for_not_found_is_valid_json() {
        let body = RpcError::NotFound.to_wire_body();
        let v: serde_json::Value = serde_json::from_str(&body).unwrap();
        assert_eq!(v["error"], "not found");
    }

    #[test]
    fn wire_body_handles_no_special_chars() {
        let err = RpcError::Internal("simple".into());
        let body = err.to_wire_body();
        assert_eq!(body, r#"{"error":"internal error: simple"}"#);
    }

    #[test]
    fn status_code_is_const_callable() {
        // Compile-time evidence the method is `const fn` — if it
        // weren't, this binding would not type-check.
        const CODE: u16 = RpcError::Unauthorized.status_code();
        assert_eq!(CODE, 401);
    }
}
